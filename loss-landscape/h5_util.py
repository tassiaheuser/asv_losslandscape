class DirFileHandler():
    """
    This class is used to handle the hdf5 files generated by the surface model.

    Args:
    - path (str): path to the hdf5 file

    Methods:
    - getDirFile: returns the directory of the file used to generate the hdf5 file
    - getCoordinates: returns the coordinates of the surface
    - getTrainLoss: returns the training loss
    - getTrainAcc: returns the training accuracy
    - __str__: prints the structure of the hdf5 file use print(DirFileHandler) to print the structure
    """
    def __init__(self,path):
        self.f = h5py.File(path, "r")
        self.path = path
    
    # with this method print(SurfaceFileHandler) will print the structure of the hdf5 file
    def __str__(self):
        print_hdf5(self.path)

    def getCoordinates(self):
        xdirection = read_list(self.f, 'xdirection')
        if 'ydirection' in self.f.keys():  # If this is a 2D plot
            ydirection = read_list(self.f, 'ydirection')
            return {"x":xdirection, "y":ydirection}
        else:
            return {"x":xdirection}
    
    def close(self):
        self.f.close()  
        